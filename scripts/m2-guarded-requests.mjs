// Builds the M2 window submissions in the form Security 0031 used in production: each write
// file from the reviewed packet ref, unchanged, preceded by the reviewed guard v3
// (scripts/sql-guard/gen-guard3.py, byte-identical to docs/security/0031-direct-route on
// claude/ops-2026-10-23, reviewed at b3d5707e). Read-only files (preflight, verifies, the
// backfill gate report) are listed to run as they are. Writes proposed/m2-guarded/:
// one request per write step, RUN-ORDER.md and SHA256SUMS. --check rebuilds in memory and
// refuses if anything committed differs. Run: node scripts/m2-guarded-requests.mjs [--check]
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const REF = process.env.M2_PACKET_REF ?? "origin/review/m2-packet-29d47ee3";
const OUT = "proposed/m2-guarded";
const check = process.argv.includes("--check");
const sha = (b) => createHash("sha256").update(b).digest("hex");
const show = (p) => execFileSync("git", ["show", `${REF}:${p}`]);
const manifest = JSON.parse(show("proposed/rehearsal/manifest.json"));
const refCommit = execFileSync("git", ["rev-parse", REF], { encoding: "utf8" }).trim();
const tmp = join(tmpdir(), `m2-guard-${process.pid}`); mkdirSync(tmp, { recursive: true });
const files = new Map(); const rows = [];
let seq = 0;
for (const e of manifest) {
  if (e.ord < 144 || e.kind === "rollback" || e.ord === 205) continue;
  const bytes = show(e.path);
  const window = e.ord <= 148 || e.ord === 207 ? 1 : 2;
  if (e.kind === "packet") {
    const f = join(tmp, "pkg.sql"); writeFileSync(f, bytes);
    const guard = execFileSync("python3", ["-I", "scripts/sql-guard/gen-guard3.py", f]);
    const name = `${String(++seq).padStart(2, "0")}-step-${e.step}.sql`;
    const request = Buffer.concat([guard, bytes]);
    files.set(name, request);
    rows.push({ window, ord: e.ord, step: e.step, kind: "guarded write", file: `${OUT}/${name}`, source: e.path, sourceSha: sha(bytes), requestSha: sha(request) });
  } else {
    rows.push({ window, ord: e.ord, step: e.step ?? "", kind: e.kind === "verify" ? "read-only verify (must return t)" : "read-only query", file: e.path, source: e.path, sourceSha: sha(bytes), requestSha: "" });
  }
}
rmSync(tmp, { recursive: true, force: true });
// Window 1 ends with the backfill gate report and the stand-down assertion; Window 2 with
// step 29's verify and the same assertion. 206 (no-executor-create) runs at the end of each.
const w1 = rows.filter((r) => r.window === 1 && r.ord !== 207), gate = rows.find((r) => r.ord === 207), stand = rows.find((r) => r.ord === 206);
const w2 = rows.filter((r) => r.window === 2 && r.ord !== 206);
const line = (r, i) => `| ${i} | ${r.step || "—"} | ${r.kind} | \`${r.file}\` | ${r.requestSha ? "`" + r.requestSha + "`" : "`" + r.sourceSha + "` (file)"} |`;
const head = "| # | Step | Kind | Submit exactly | SHA-256 |\n|---|---|---|---|---|";
const md = `# M2 window run order (generated by scripts/m2-guarded-requests.mjs; do not edit)

Packet ref \`${REF}\` = \`${refCommit}\`. Guarded writes = reviewed guard v3 + the unchanged
packet file; each is one Lovable \`query_database\` call (one transaction). Read-only files run
as they are. Every write's verify must return \`t\` before the next write.

## Window 1 (Release A live)

${head}
${[...w1, null].map((r, i) => r ? line(r, i + 1) : `| ${i + 1} | — | operator, not SQL | \`bun scripts/backfill-document-content-sha.ts --url <project>\` then \`--write\` (must end missing=0 mismatched=0 storage_errors=0) | — |`).join("\n")}
${line(gate, w1.length + 2)}
${line(stand, w1.length + 3)}

## Window 2 (Release B live)

${head}
${w2.map((r, i) => line(r, i + 1)).join("\n")}
${line(stand, w2.length + 1)}
`;
const sums = [...files].map(([n, b]) => `${sha(b)}  ${n}`).join("\n") + "\n";
if (check) {
  let bad = 0;
  for (const [n, b] of files) { let cur; try { cur = readFileSync(join(OUT, n)); } catch { cur = null; } if (!cur || !cur.equals(b)) { console.error(`differs: ${n}`); bad++; } }
  if (readFileSync(join(OUT, "RUN-ORDER.md"), "utf8") !== md) { console.error("differs: RUN-ORDER.md"); bad++; }
  if (readFileSync(join(OUT, "SHA256SUMS"), "utf8") !== sums) { console.error("differs: SHA256SUMS"); bad++; }
  if (bad) process.exit(1);
  console.log(`m2 guarded requests: ${files.size} requests match ${refCommit.slice(0, 8)}`);
} else {
  rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT, { recursive: true });
  for (const [n, b] of files) writeFileSync(join(OUT, n), b);
  writeFileSync(join(OUT, "RUN-ORDER.md"), md); writeFileSync(join(OUT, "SHA256SUMS"), sums);
  console.log(`wrote ${files.size} guarded requests to ${OUT}`);
}
