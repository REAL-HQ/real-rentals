#!/usr/bin/env bash
# ===========================================================================
# THE RULES THIS FILE EXISTS FOR:
#
#   THE STAGING SEQUENCE INSTALLS CLEANLY, ROLLS BACK WHOLE, REFUSES TO
#   REPLAY, REFUSES TO RUN TWICE AT ONCE, REFUSES DRIFT, AND LEAVES THE
#   NINE EXISTING RECEIPTS ALONE — NAME, CHECKSUM AND ORDER. RLS LETS A
#   MANAGER READ AN AGREEMENT AND A DRIVER READ ONLY THEIR OWN. SIGNED
#   PDFs ARE NOT READABLE FROM STORAGE. NUMBERS ARE UNIQUE AND IMMUTABLE.
#   THE STORAGE POLICY IS REFUSED TO AN UNPRIVILEGED ROLE AND APPLIED BY A
#   PRIVILEGED ONE — AND stage10 WILL NOT RUN WITHOUT IT.
#
# The ledger here is (stage, sha256, installed_at), the shape verified on
# staging. The nine receipts it is seeded with are SYNTHETIC: the real nine
# were read during verification and are not known to this package, which is
# why baseline-receipts.json ships UNPOPULATED. What is tested here is the
# comparison MECHANISM, against a manifest generated by the very query that
# file documents.
#
# Everything runs against a DISPOSABLE PostgreSQL cluster created in a temp
# directory and destroyed at the end. No hosted database is touched, no
# network is used, and no production object is referenced.
#
# Run: bash scripts/esign-staging-install.test.sh   (npm run test:esign-staging)
# ===========================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PKG="$HERE/scripts/esign-staging"
REL="$HERE/scripts/esign-release"
PGBIN="$(ls -d /usr/lib/postgresql/*/bin 2>/dev/null | sort -V | tail -1)"
[ -x "$PGBIN/initdb" ] || { echo "no local PostgreSQL found under /usr/lib/postgresql"; exit 1; }

# PostgreSQL refuses to run as root, so the disposable cluster runs as the
# unprivileged postgres user. AS_PG wraps every server-side command; psql
# itself is a client and runs as whoever invoked the script.
D="$(mktemp -d)"; PORT=55439
chmod 777 "$D"
AS_PG=""
if [ "$(id -u)" = 0 ] && id postgres >/dev/null 2>&1; then
  AS_PG="runuser -u postgres --"
  command -v runuser >/dev/null 2>&1 || AS_PG="su postgres -c"
fi
pg() { if [ -n "$AS_PG" ]; then runuser -u postgres -- "$@"; else "$@"; fi; }
fail=0
ok() { if [ "$1" = 0 ]; then echo "  PASS  $2"; else fail=$((fail+1)); echo "  BLOCKER  $2"; fi; }
cleanup() { pg "$PGBIN/pg_ctl" -D "$D/data" -m immediate stop >/dev/null 2>&1; rm -rf "$D"; }
trap cleanup EXIT

pg "$PGBIN/initdb" -D "$D/data" -U postgres -A trust >/dev/null 2>&1
pg "$PGBIN/pg_ctl" -D "$D/data" -o "-p $PORT -k $D -c listen_addresses=''" -l "$D/log" -w start >/dev/null 2>&1 \
  || { echo "could not start the disposable cluster"; cat "$D/log"; exit 1; }
PSQL="$PGBIN/psql -h $D -p $PORT -U postgres -v ON_ERROR_STOP=1 -q"
Q() { $PGBIN/psql -h "$D" -p "$PORT" -U postgres -Atc "$1" esign 2>&1; }

$PSQL -d postgres -c "create database esign" >/dev/null

# --------------------------------------------------- the stand-in backend
# Just enough of the hosted shape for the package to install against: the
# roles, the schemas, the prerequisite tables the baseline references, the
# private helpers, and the staging ledger carrying its nine existing
# receipts. These are PREREQUISITES, not part of the package under test.
$PSQL -d esign >/dev/null <<'SQL'
CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN;
CREATE SCHEMA private; CREATE SCHEMA storage; CREATE SCHEMA auth;
-- Supabase installs pgcrypto into the extensions schema, and 0023 calls
-- extensions.digest() to hash template bodies. Same shape here.
CREATE SCHEMA extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT USAGE ON SCHEMA private TO service_role;
GRANT USAGE ON SCHEMA extensions TO anon, authenticated, service_role;
GRANT USAGE ON SCHEMA storage TO anon, authenticated, service_role;

CREATE TYPE app_role AS ENUM ('admin','user','partner','driver','team','coordinator');
CREATE TABLE public.user_roles (user_id uuid NOT NULL, role app_role NOT NULL);
CREATE TABLE public.applications (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid, full_name text);
CREATE TABLE public.vehicles (id uuid PRIMARY KEY DEFAULT gen_random_uuid());
CREATE TABLE public.rentals (id uuid PRIMARY KEY DEFAULT gen_random_uuid());
CREATE TABLE public.documents (id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  storage_bucket text, storage_path text, visibility text[], partner_id uuid);

-- auth.uid() is set per-test with a session GUC.
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS
  $$ SELECT nullif(current_setting('test.uid', true),'')::uuid $$;
CREATE FUNCTION private.is_staff() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS
  $$ SELECT EXISTS (SELECT 1 FROM public.user_roles WHERE user_id=auth.uid() AND role::text IN ('admin','team','coordinator')) $$;
CREATE FUNCTION private.is_manager() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS
  $$ SELECT EXISTS (SELECT 1 FROM public.user_roles WHERE user_id=auth.uid() AND role::text IN ('admin','team')) $$;
CREATE FUNCTION private.has_role(_user_id uuid, _role app_role) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS
  $$ SELECT EXISTS (SELECT 1 FROM public.user_roles WHERE user_id=_user_id AND role=_role) $$;
CREATE FUNCTION private.is_partner_owner(_p uuid) RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT false $$;

CREATE TABLE storage.buckets (id text PRIMARY KEY, name text, public boolean DEFAULT false,
  file_size_limit bigint, allowed_mime_types text[]);
CREATE TABLE storage.objects (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), bucket_id text, name text);
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON storage.objects TO authenticated;

-- Hosted Supabase: storage.objects is owned by supabase_storage_admin and the
-- installer's role is NOT a member, while storage.buckets stays writable.
-- Reproduced here, or the privilege gate in 03 can never be exercised and the
-- split between the two files would be untested theatre.
CREATE ROLE supabase_storage_admin NOLOGIN;
ALTER TABLE storage.objects OWNER TO supabase_storage_admin;
-- A non-superuser stand-in for the ordinary staging connection.
CREATE ROLE unpriv_installer NOLOGIN;
GRANT USAGE ON SCHEMA storage, public, private TO unpriv_installer;
GRANT SELECT ON storage.objects, public.documents TO unpriv_installer;

-- The staging ledger, with the nine receipts through Stage 09 that must
-- survive untouched.
-- Hosted Supabase grants `authenticated` SELECT on these; the driver policy
-- subqueries applications and the partner storage policy subqueries
-- documents, and a policy is evaluated with the CALLER's privileges on the
-- tables it reads. Without these the policies fail closed for the wrong
-- reason and the RLS results below would be meaningless.
GRANT SELECT ON public.applications, public.documents, public.user_roles TO authenticated;

-- installed_at, not applied_at: the column name verified on staging. Nine
-- receipts at distinct, increasing times, so "ordering" is a real property
-- and not an artefact of them all sharing one now().
CREATE TABLE private.staging_install_receipts (
  stage text PRIMARY KEY, sha256 text NOT NULL, installed_at timestamptz NOT NULL DEFAULT now());
INSERT INTO private.staging_install_receipts (stage, sha256, installed_at)
SELECT 'stage0'||g||'_synthetic', md5('stage'||g)||md5('salt'||g),
       timestamptz '2026-09-01 00:00:00+00' + (g || ' hours')::interval
  FROM generate_series(1,9) g;
SQL

PRE_RECEIPTS="$(Q "select count(*) from private.staging_install_receipts")"
PRE_DIGEST="$(Q "select md5(string_agg(stage||sha256||installed_at, '|' order by installed_at, stage)) from private.staging_install_receipts")"

# ------------------------------------------------- the pinned nine receipts
# Generated by the EXACT read-only query documented in the header of
# baseline-receipts.json, so this also proves that query yields a manifest
# the installer accepts.
MANIFEST="$D/baseline-receipts.json"
$PGBIN/psql -h "$D" -p "$PORT" -U postgres -Atq -d esign > "$MANIFEST" <<'SQL'
SELECT jsonb_pretty(jsonb_build_object(
  'status','VERIFIED',
  'database', current_database(),
  'captured_at', now(),
  'receipts', (SELECT jsonb_agg(jsonb_build_object(
       'ordinal', ord, 'stage', stage, 'sha256', sha256) ORDER BY ord)
     FROM (SELECT row_number() OVER (ORDER BY installed_at, stage) AS ord, stage, sha256
             FROM private.staging_install_receipts) r)));
SQL
# The installer's own reader, not a reimplementation of it.
. "$PKG/manifest.sh"
BASELINE_DIGEST="$(jread digest)"
EXPECT_DB="$(jread database)"

echo
echo "================= the pinned baseline is read the same way by every tool"
[ "$(jread status)" = "VERIFIED" ]; ok $? "the captured manifest reads as VERIFIED"
[ "$(jread count)" = "9" ]; ok $? "it pins nine receipts"
[ "$EXPECT_DB" = "esign" ]; ok $? "it records the database it was captured from ($EXPECT_DB)"
# A digest that changed with the operator's toolchain would make the pin
# worthless, so all three backends must agree byte for byte.
D_JQ=""; D_PY=""; D_NODE=""
command -v jq >/dev/null 2>&1 && D_JQ="$(jq -r '[(.receipts // []) | sort_by(.ordinal)[] | "\(.ordinal):\(.stage):\(.sha256)"] | join("|")' "$MANIFEST")"
command -v python3 >/dev/null 2>&1 && D_PY="$(python3 -c '
import json,sys
m=json.load(open(sys.argv[1]))
rs=sorted(m.get("receipts") or [], key=lambda r: r["ordinal"])
print("|".join("%d:%s:%s"%(r["ordinal"],r["stage"],r["sha256"]) for r in rs))' "$MANIFEST")"
command -v node >/dev/null 2>&1 && D_NODE="$(node -e '
const m=JSON.parse(require("fs").readFileSync(process.argv[1],"utf8"));
const rs=(m.receipts||[]).slice().sort((a,b)=>a.ordinal-b.ordinal);
console.log(rs.map(r=>`${r.ordinal}:${r.stage}:${r.sha256}`).join("|"));' "$MANIFEST")"
N_AGREE=0
for d in "$D_JQ" "$D_PY" "$D_NODE"; do [ -n "$d" ] && [ "$d" = "$BASELINE_DIGEST" ] && N_AGREE=$((N_AGREE+1)); done
[ "$N_AGREE" -ge 2 ]; ok $? "jq, python3 and node agree on the digest ($N_AGREE of 3 available agreed)"
echo "$BASELINE_DIGEST" | grep -q '^1:stage01_synthetic:'; ok $? "the digest starts at ordinal 1, in installed_at order"

# install.sh drives psql over TCP; here the cluster is socket-only, so the
# stages are replayed the same way install.sh composes them. The payloads,
# preflight and postflight are the real package files.
# DIGEST_OVERRIDE lets the drift tests hand preflight a baseline that does
# not match the ledger, which is the only way to prove the comparison bites.
DIGEST_OVERRIDE=""
stage() {
  local name="$1" expect="$2" sha="$3"; shift 3
  local digest="${DIGEST_OVERRIDE:-$BASELINE_DIGEST}"
  { echo "\\set ON_ERROR_STOP on"
    echo "\\set stage_name '$name'"; echo "\\set payload_sha '$sha'"
    echo "\\set expect_receipt $expect"
    echo "\\set baseline_digest '$digest'"
    echo "\\set expect_database '$EXPECT_DB'"
    echo "BEGIN;"
    echo "\\i $PKG/preflight.sql"
    for f in "$@"; do echo "\\i $f"; done
    echo "INSERT INTO private.staging_install_receipts (stage, sha256, installed_at) VALUES (:'stage_name', :'payload_sha', now());"
    echo "\\set expect_receipt_after $((expect+1))"
    echo "\\i $PKG/postflight.sql"
    echo "COMMIT;"
  } | $PGBIN/psql -h "$D" -p "$PORT" -U postgres -v ON_ERROR_STOP=1 -q esign 2>&1
}

echo
echo "================= the storage policy needs a privileged path"
# The ordinary connection cannot CREATE POLICY on storage.objects, so 03 is
# not driven by install.sh at all. Prove the refusal first, then that stage10
# will not proceed without the policy, then apply it the privileged way.
OUT="$($PGBIN/psql -h "$D" -p "$PORT" -U postgres -v ON_ERROR_STOP=1 -q -d esign 2>&1 <<SQL
BEGIN; SET LOCAL ROLE unpriv_installer;
\\i $PKG/03_storage_policy.privileged.sql
COMMIT;
SQL
)"
echo "$OUT" | grep -qi "cannot CREATE POLICY on storage.objects"
ok $? "an unprivileged role is refused, and told which path to use"
echo "$OUT" | grep -qi "supabase_storage_admin"
ok $? "  the refusal names the owner it would need to be"
[ "$(Q "select count(*) from pg_policies where schemaname='storage' and tablename='objects'")" = "0" ]
ok $? "  and no policy was created by the attempt"
# No escalation anywhere in the package. Executable lines only: 03's own
# header says in prose that it does NOT do these things, and a grep that
# counted the promise as the offence would fail on honesty.
cat "$PKG"/*.sql | sed -e 's/--.*$//' \
  | grep -qiE 'ALTER TABLE[^;]*OWNER TO|ALTER ROLE|GRANT [a-z_]+ TO (postgres|authenticated|service_role)[[:space:]]*;'
[ $? -ne 0 ]; ok $? "the package never changes ownership or grants a role to work around it"

# stage10 must refuse while the policy is missing: a bucket without it is a
# partial installation of the reviewed design.
OUT="$(stage stage10_agreements_baseline 9 "basesha:storsha" "$PKG/01_agreements_baseline.sql" "$PKG/02_private_storage.sql" 2>&1)"
RC=$?
[ $RC -ne 0 ] && echo "$OUT" | grep -qi 'is not present. It must be applied FIRST, through the privileged path'
ok $? "stage10 refuses while the privileged storage policy is absent"
echo "$OUT" | grep -qi 'supabase_storage_admin'
ok $? "  naming the owner, so the operator knows which path is meant"
[ "$(Q "select to_regclass('public.agreements') is null")" = "t" ]; ok $? "  and created nothing on the way to refusing"
[ "$(Q "select count(*) from private.staging_install_receipts")" = "9" ]; ok $? "  the ledger is still the nine"

# Now the privileged path: in this disposable cluster postgres is a superuser,
# which is what a provider-assisted execution looks like from the outside.
OUT="$($PGBIN/psql -h "$D" -p "$PORT" -U postgres -v ON_ERROR_STOP=1 -q -d esign -f "$PKG/03_storage_policy.privileged.sql" 2>&1)"
[ $? = 0 ]; ok $? "a privileged role applies the policy${OUT:+ — $OUT}"
[ "$(Q "select count(*) from pg_policies where schemaname='storage' and tablename='objects' and policyname='Partners read their driver documents'")" = "1" ]
ok $? "  the reviewed partner read policy is present, once"
OUT="$($PGBIN/psql -h "$D" -p "$PORT" -U postgres -v ON_ERROR_STOP=1 -q -d esign -f "$PKG/03_storage_policy.privileged.sql" 2>&1)"
[ $? = 0 ] && [ "$(Q "select count(*) from pg_policies where schemaname='storage' and tablename='objects'")" = "1" ]
ok $? "  re-running it is a no-op, not a duplicate"

echo
echo "================= the sequence installs cleanly"
OUT="$(stage stage10_agreements_baseline 9 "basesha:storsha" "$PKG/01_agreements_baseline.sql" "$PKG/02_private_storage.sql")"
ok $? "stage10 (baseline + private storage) commits${OUT:+ — $OUT}"
OUT="$(stage stage11_esign_0023 10 "675bff0e8cba301581209c6c2a4f4cd7d485676c47a9e3920de87622c129acc7" "$REL/0023_esign_template_versioning_library.sql")"
ok $? "stage11 (0023) commits${OUT:+ — $OUT}"
OUT="$(stage stage12_esign_0024 11 "199f57eda905ef73f9d531f813abc8b2f16759a8b0e89b6920f2985ba55d9aa8" "$REL/0024_esign_agreement_numbering.sql")"
ok $? "stage12 (0024) commits${OUT:+ — $OUT}"

echo
echo "================= the existing nine receipts are untouched"
NOW_DIGEST="$(Q "select md5(string_agg(stage||sha256||installed_at,'|' order by installed_at, stage)) from private.staging_install_receipts where stage like 'stage0%'")"
[ "$NOW_DIGEST" = "$PRE_DIGEST" ]; ok $? "the nine are byte-identical — name, checksum and timestamp"
[ "$(Q "select count(*) from private.staging_install_receipts")" = "12" ]; ok $? "the ledger holds 12 receipts (9 + 3)"
[ "$(Q "select sha256 from private.staging_install_receipts where stage='stage11_esign_0023'")" = "675bff0e8cba301581209c6c2a4f4cd7d485676c47a9e3920de87622c129acc7" ]
ok $? "the reviewed 0023 checksum is what was recorded"

echo
echo "================= the journal receipts are correct"
[ "$(Q "select sha256 from private.staging_install_receipts where stage='stage12_esign_0024'")" = "199f57eda905ef73f9d531f813abc8b2f16759a8b0e89b6920f2985ba55d9aa8" ]
ok $? "the reviewed 0024 checksum too"
[ "$(Q "select sha256 from private.staging_install_receipts where stage='stage10_agreements_baseline'")" = "basesha:storsha" ]
ok $? "stage10 records both payload hashes"
# The baseline comparison keys on install order, so a backdated receipt would
# make the pinned nine unreadable.
[ "$(Q "select string_agg(stage,'>' order by installed_at, stage) from private.staging_install_receipts where stage like 'stage1%'")" = "stage10_agreements_baseline>stage11_esign_0023>stage12_esign_0024" ]
ok $? "the three are ordered 10 -> 11 -> 12 by installed_at"
[ "$(Q "select (select min(installed_at) from private.staging_install_receipts where stage like 'stage1%') > (select max(installed_at) from private.staging_install_receipts where stage like 'stage0%')")" = "t" ]
ok $? "and all three land after the nine, never backdated"
[ "$(Q "select count(*) from private.staging_install_receipts where sha256 is null or sha256=''")" = "0" ]
ok $? "no receipt was written without a checksum"

echo
echo "================= two installers at once are refused"
# A second installer must be told to stop, not left blocking. The first holds
# the transaction-scoped advisory lock; the stage attempted underneath it has
# to fail fast and leave nothing behind.
# Named, so it can be terminated from SQL rather than by guessing at a PID.
# A locker that outlives this block holds the advisory lock over every later
# stage, and each one then refuses for the WRONG reason — which looks like a
# passing test and proves nothing.
PGAPPNAME=esign_lock_probe $PGBIN/psql -h "$D" -p "$PORT" -U postgres -q -d esign -c \
  "begin; select pg_advisory_xact_lock(4919, hashtext('esign_staging_install')); select pg_sleep(30); commit;" >/dev/null 2>&1 &
for _ in $(seq 1 40); do
  [ "$(Q "select count(*) from pg_locks where locktype='advisory' and classid=4919 and granted")" != "0" ] && break
  sleep 0.25
done
[ "$(Q "select count(*) from pg_locks where locktype='advisory' and classid=4919 and granted")" != "0" ]
ok $? "the first installer holds the install lock"
OUT="$(stage stage13_concurrent_probe 12 "deadbeef" "$PKG/01_agreements_baseline.sql" 2>&1)"
[ $? -ne 0 ] && echo "$OUT" | grep -qi "holds the install lock"
ok $? "a second stage is refused while it is held"
[ "$(Q "select count(*) from private.staging_install_receipts")" = "12" ]; ok $? "  and wrote no receipt"
$PSQL -d esign -c "select pg_terminate_backend(pid) from pg_stat_activity where application_name='esign_lock_probe'" >/dev/null 2>&1
wait 2>/dev/null
# Transaction-scoped, so it is gone with no cleanup step to forget.
for _ in $(seq 1 60); do
  [ "$(Q "select count(*) from pg_locks where locktype='advisory' and classid=4919 and granted")" = "0" ] && break
  sleep 0.25
done
[ "$(Q "select count(*) from pg_locks where locktype='advisory' and classid=4919 and granted")" = "0" ]
ok $? "  and the lock released itself when that transaction ended"

echo
echo "================= drift is refused"
# 1. A baseline that does not match the ledger. This is the check that both
#    protects Stage 01-09 and binds the install to the verified database.
DIGEST_OVERRIDE="1:stage01_synthetic:$(printf 'f%.0s' $(seq 1 64))"
OUT="$(stage stage14_drift_probe 12 "deadbeef" "$PKG/01_agreements_baseline.sql" 2>&1)"
[ $? -ne 0 ] && echo "$OUT" | grep -qi "not the nine that were verified"
ok $? "a ledger that does not match the pinned baseline is refused"
echo "$OUT" | grep -qi "pinned:"; ok $? "  and the refusal prints both the pinned and the live value"
DIGEST_OVERRIDE=""
# 2. A blank baseline — an UNPOPULATED manifest reaching SQL anyway.
DIGEST_OVERRIDE=" "
OUT="$(stage stage14_drift_probe 12 "deadbeef" "$PKG/01_agreements_baseline.sql" 2>&1)"
[ $? -ne 0 ]; ok $? "a blank baseline is refused, not read as 'nothing to check'"
DIGEST_OVERRIDE=""
# 3. The wrong database.
SAVED_DB="$EXPECT_DB"; EXPECT_DB="not_this_database"
OUT="$(stage stage14_drift_probe 12 "deadbeef" "$PKG/01_agreements_baseline.sql" 2>&1)"
[ $? -ne 0 ] && echo "$OUT" | grep -qi "not the verified staging target"
ok $? "a connection to the wrong database is refused"
EXPECT_DB="$SAVED_DB"
# 4. An extra pre-existing receipt: somebody installed something since review.
$PSQL -d esign -c "insert into private.staging_install_receipts (stage, sha256) values ('stage99_interloper', repeat('e',64))" >/dev/null
OUT="$(stage stage14_drift_probe 13 "deadbeef" "$PKG/01_agreements_baseline.sql" 2>&1)"
[ $? -ne 0 ] && echo "$OUT" | grep -qi "pre-existing receipt"
ok $? "an unexpected extra receipt is refused"
$PSQL -d esign -c "delete from private.staging_install_receipts where stage='stage99_interloper'" >/dev/null
# 5. Partial schema: some agreements objects present, some not.
$PSQL -d esign -c "alter table public.esign_recipients rename to esign_recipients_moved" >/dev/null
OUT="$(stage stage14_drift_probe 12 "deadbeef" "$PKG/01_agreements_baseline.sql" 2>&1)"
[ $? -ne 0 ] && echo "$OUT" | grep -qi "partial agreements schema"
ok $? "a partially-present agreements schema is refused"
$PSQL -d esign -c "alter table public.esign_recipients_moved rename to esign_recipients" >/dev/null
# 6. A policy other than the reviewed partner read reaching the bucket.
$PSQL -d esign -c "create policy \"sneaky bucket read\" on storage.objects for select to authenticated using (bucket_id = 'rental-agreements')" >/dev/null
OUT="$(stage stage14_drift_probe 12 "deadbeef" "$PKG/01_agreements_baseline.sql" 2>&1)"
[ $? -ne 0 ] && echo "$OUT" | grep -qi "other than the reviewed partner read"
ok $? "an extra storage policy reaching the bucket is refused"
$PSQL -d esign -c "drop policy \"sneaky bucket read\" on storage.objects" >/dev/null
[ "$(Q "select count(*) from private.staging_install_receipts")" = "12" ]
ok $? "none of the six refusals wrote a receipt"

echo
echo "================= replay is refused"
OUT="$(stage stage11_esign_0023 12 "675bff0e8cba301581209c6c2a4f4cd7d485676c47a9e3920de87622c129acc7" "$REL/0023_esign_template_versioning_library.sql" 2>&1)"
[ $? -ne 0 ] && echo "$OUT" | grep -qi "already recorded"; ok $? "a second run of stage11 is refused by name"
[ "$(Q "select count(*) from private.staging_install_receipts")" = "12" ]; ok $? "  and the ledger is unchanged by the refusal"

echo
echo "================= a failing stage rolls back whole"
# A payload that does real work and then fails. Nothing it did may survive,
# and no receipt may be written for it.
cat > "$D/bad.sql" <<'SQL'
CREATE TABLE public.rollback_canary (id int);
INSERT INTO public.agreement_templates (name, body) VALUES ('canary','x');
SELECT 1/0;
SQL
OUT="$(stage stage13_rollback_probe 12 "deadbeef" "$D/bad.sql" 2>&1)"
[ $? -ne 0 ]; ok $? "a stage whose payload fails does not commit"
[ "$(Q "select to_regclass('public.rollback_canary') is null")" = "t" ]; ok $? "  the table it created is gone"
[ "$(Q "select count(*) from public.agreement_templates where name='canary'")" = "0" ]; ok $? "  the row it inserted is gone"
[ "$(Q "select count(*) from private.staging_install_receipts where stage='stage13_rollback_probe'")" = "0" ]; ok $? "  and no receipt was left behind"
[ "$(Q "select count(*) from private.staging_install_receipts")" = "12" ]; ok $? "  the ledger still holds exactly 12"

echo
echo "================= a payload that rewrites history is caught after the fact"
# Preflight proves the nine match BEFORE the payload runs. This is the other
# half: a payload that edits a historical receipt on its way past would
# otherwise commit silently, and the ledger is the only record of what
# staging has had installed.
cat > "$D/tamper.sql" <<'SQL'
UPDATE private.staging_install_receipts
   SET sha256 = repeat('9',64)
 WHERE stage = 'stage05_synthetic';
SQL
OUT="$(stage stage15_tamper_probe 12 "deadbeef" "$D/tamper.sql" 2>&1)"
