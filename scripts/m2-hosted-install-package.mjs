// Hosted M2 installation package: the approved packet unchanged, plus the two
// step-3 amendments and the three hosted rollback variants, with checksums.
// Every approved file is checked byte for byte against the approved commit.
//   node scripts/m2-hosted-install-package.mjs           write the package files
//   node scripts/m2-hosted-install-package.mjs --check   fail if anything drifted
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";

export const APPROVED = "29d47ee3";
export const OUT = "proposed/m2-hosted-install";
const sha = (b) => createHash("sha256").update(b).digest("hex");
const approvedBlob = (path) => {
  try { return execFileSync("git", ["show", `${APPROVED}:${path}`], { maxBuffer: 1 << 26, stdio: ["ignore", "pipe", "ignore"] }); } catch { return null; }
};

export function packageEntries() {
  const manifest = JSON.parse(readFileSync("proposed/rehearsal/manifest.json", "utf8"));
  const rows = [];
  for (const e of manifest.filter((x) => x.ord >= 144)) {
    const amendment = e.path.startsWith("proposed/m2-hosted-amendments/");
    const role = e.kind === "query" ? (e.path.endsWith("m2-preflight.sql") ? "preflight" : "backfill-report")
      : e.kind === "packet" ? (amendment ? "amendment" : "install")
      : e.kind === "verify" ? "verify" : amendment ? "rollback-hosted" : "rollback";
    const bytes = readFileSync(e.path);
    if (sha(bytes) !== e.sha256) throw new Error(`${e.path} differs from the rehearsed manifest`);
    let origin = amendment ? "hosted amendment (new)" : "approved, unchanged";
    if (!amendment) {
      const blob = approvedBlob(e.path);
      if (blob) { if (!blob.equals(bytes)) throw new Error(`${e.path} differs from approved ${APPROVED}`); origin = `byte-identical to ${APPROVED}`; }
      else origin = e.path.startsWith("proposed/rehearsal/verify/") ? "generated verbatim from HOSTED-INSTALL.md"
        : e.path.startsWith("proposed/m2-verify/") ? "read-only review assertion" : "added after approval";
    }
    rows.push({ ord: e.ord, step: e.meta?.step ?? e.step ?? "", role, path: e.path, sha256: e.sha256, origin });
  }
  return rows;
}

function variantsDiff() {
  const pairs = [["01-auth-binding.sql"], ["03-record-rental.sql"], ["05-evidence.sql"]];
  let out = "";
  for (const [f] of pairs) {
    try { execFileSync("git", ["diff", "--no-index", "--no-color", `proposed/rollback/${f}`, `proposed/m2-hosted-amendments/rollback/${f}`]); }
    catch (e) { out += e.stdout.toString(); }
  }
  return out;
}

export function build() {
  const rows = packageEntries();
  if (rows.some((r) => r.origin.startsWith("added after approval"))) throw new Error("an install-path file is neither approved nor a declared amendment");
  const sums = rows.map((r) => `${r.sha256}  ${r.path}`).filter((l, i, a) => a.indexOf(l) === i).join("\n") + "\n";
  const table = ["| Ord | Step | Role | File | SHA-256 (first 16) | Origin |", "|---:|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.ord} | ${r.step} | ${r.role} | \`${r.path}\` | \`${r.sha256.slice(0, 16)}\` | ${r.origin} |`)].join("\n") + "\n";
  return { "SHA256SUMS": sums, "MANIFEST.md": `# Hosted M2 package manifest\n\nGenerated by \`scripts/m2-hosted-install-package.mjs\`. Do not edit.\n\n${table}`, "ROLLBACK-VARIANTS.diff": variantsDiff() };
}

if (process.argv[1]?.endsWith("m2-hosted-install-package.mjs")) {
  const files = build();
  mkdirSync(OUT, { recursive: true });
  for (const [name, text] of Object.entries(files)) {
    const p = `${OUT}/${name}`;
    if (process.argv.includes("--check")) {
      if (!existsSync(p) || readFileSync(p, "utf8") !== text) { console.error(`${p} has drifted`); process.exit(1); }
    } else writeFileSync(p, text);
  }
  const rows = packageEntries();
  const by = (k) => rows.filter((r) => r.role === k).length;
  console.log(`${process.argv.includes("--check") ? "checked" : "wrote"} ${OUT}: install=${by("install")} amendment=${by("amendment")} verify=${by("verify")} rollback=${by("rollback")} rollback-hosted=${by("rollback-hosted")}; approved files byte-identical to ${APPROVED}: ${rows.filter((r) => r.origin.startsWith("byte-identical")).length}`);
}
