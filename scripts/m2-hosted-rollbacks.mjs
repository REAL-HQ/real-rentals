// Hosted variants of the three role-dropping rollbacks (steps 1, 5, 7).
//
// The approved rollbacks were generated from a local superuser catalog. On a
// hosted Supabase database, where postgres is not a superuser, exactly two
// statements in each file fail (probed on the disposable rehearsal, 2026-10-23):
//   REVOKE ALL ON ALL FUNCTIONS IN SCHEMA "vault" FROM <role>  -> 42501
//     (vault functions belong to supabase_admin; the rr_ roles never hold grants there)
//   DROP OWNED BY <role>                                        -> 42501
//     (needs postgres to inherit the role; CREATE ROLE gave postgres ADMIN only)
// Each variant is the original byte for byte, minus that one REVOKE line and
// plus one GRANT ... WITH INHERIT TRUE line immediately before DROP OWNED BY.
// DROP ROLE, a few lines later, removes that membership with the role.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

export const HOSTED_ROLLBACKS = [
  { step: 1, file: "01-auth-binding.sql", role: "rr_approval_executor" },
  { step: 5, file: "03-record-rental.sql", role: "rr_record_executor" },
  { step: 7, file: "05-evidence.sql", role: "rr_evidence_issuer" },
];
export const OUT_DIR = "proposed/m2-hosted-amendments/rollback";

export function hostedVariant(original, role) {
  const vault = `REVOKE ALL ON ALL FUNCTIONS IN SCHEMA "vault" FROM "${role}";`;
  const drop = `DROP OWNED BY "${role}";`;
  const lines = original.split("\n");
  if (lines.filter((l) => l === vault).length !== 1) throw new Error(`${role}: expected exactly one vault REVOKE line`);
  if (lines.filter((l) => l === drop).length !== 1) throw new Error(`${role}: expected exactly one DROP OWNED BY line`);
  const out = [];
  for (const l of lines) {
    if (l === vault) continue;
    if (l === drop) out.push(`GRANT "${role}" TO postgres WITH INHERIT TRUE;`);
    out.push(l);
  }
  const header = [
    `-- HOSTED VARIANT of proposed/rollback/${"$FILE"}, generated by scripts/m2-hosted-rollbacks.mjs.`,
    `-- Identical to the approved rollback except: the vault-functions REVOKE line is`,
    `-- removed, and GRANT "${role}" TO postgres WITH INHERIT TRUE precedes DROP OWNED BY.`,
    `-- Use on hosted Supabase, where postgres is not a superuser. Do not edit by hand.`,
  ];
  return { header, body: out.join("\n") };
}

export function build() {
  return HOSTED_ROLLBACKS.map(({ step, file, role }) => {
    const original = readFileSync(`proposed/rollback/${file}`, "utf8");
    const { header, body } = hostedVariant(original, role);
    return { step, file, role, path: `${OUT_DIR}/${file}`, text: header.join("\n").replace("$FILE", file) + "\n" + body };
  });
}

if (process.argv[1]?.endsWith("m2-hosted-rollbacks.mjs")) {
  mkdirSync(OUT_DIR, { recursive: true });
  for (const v of build()) {
    if (process.argv.includes("--check")) {
      if (readFileSync(v.path, "utf8") !== v.text) { console.error(`${v.path} has drifted`); process.exit(1); }
    } else writeFileSync(v.path, v.text);
    console.log(`${process.argv.includes("--check") ? "matches" : "wrote"} ${v.path}`);
  }
}
